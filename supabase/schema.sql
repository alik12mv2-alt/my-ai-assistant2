-- زرین آرمان: schema for shared product catalog
-- Run this file in Supabase SQL Editor.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(14,0) not null default 0 check (price >= 0),
  weight numeric(8,3) not null default 0 check (weight >= 0),
  karat text not null default '۱۸ عیار',
  image_url text,
  description text,
  featured boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.products enable row level security;
alter table public.admin_users enable row level security;

-- Visitors can read active products only.
drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
on public.products for select
using (active = true);

-- Only explicitly listed admin accounts can manage products.
drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products"
on public.products for all
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

-- Users cannot self-register as admins or read the admin list.
drop policy if exists "Admins can read own admin row" on public.admin_users;
create policy "Admins can read own admin row"
on public.admin_users for select
using (user_id = auth.uid());

